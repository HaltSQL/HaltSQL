// Marks dist/cjs as CommonJS so Node loads it with require() even though the
// package itself is "type": "module", and replaces dist/cjs/meta.js: tsc emits
// `import.meta.url` verbatim, which is a SyntaxError in a CommonJS module.
import { readFileSync, writeFileSync } from "node:fs";

writeFileSync(
  new URL("../dist/cjs/package.json", import.meta.url),
  JSON.stringify({ type: "commonjs" }) + "\n",
);

const meta = new URL("../dist/cjs/meta.js", import.meta.url);
if (!readFileSync(meta, "utf8").includes("import.meta.url")) {
  throw new Error("dist/cjs/meta.js no longer contains import.meta.url; update write-cjs-package.mjs");
}
writeFileSync(
  meta,
  `"use strict";
// Generated by scripts/write-cjs-package.mjs (CommonJS equivalent of src/meta.ts).
Object.defineProperty(exports, "__esModule", { value: true });
exports.moduleUrl = void 0;
exports.moduleUrl = require("node:url").pathToFileURL(__filename).href;
`,
);
