#!/usr/bin/env bash
# HaltSQL end-to-end stack (test/e2e/compose.yaml, Compose project haltsql-e2e).
#
#   test/e2e/stack.sh env     generate test/e2e/.env (random secrets, mode 0600) if missing
#   test/e2e/stack.sh up      env + start every service and wait until healthy
#   test/e2e/stack.sh venv    create test/e2e/.venv with the pinned pytest driver,
#                             and test/e2e/.venv-agents/<pkg> for test_agents.py
#   test/e2e/stack.sh test [PYTEST ARGS...]   run pytest against the running stack
#   test/e2e/stack.sh run     up + venv + test, then down (KEEP=1 keeps the stack)
#   test/e2e/stack.sh down    stop the stack and delete its volumes
#   test/e2e/stack.sh ps|logs [SERVICE]
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
env_file="${HALTSQL_E2E_ENV_FILE:-$here/.env}"
venv="$here/.venv"
agents_venvs="$here/.venv-agents"
# Agent frameworks used by test_agents.py. Their dependency pins conflict, so
# each gets its own virtualenv, installed from integrations/<pkg> with that
# package's constraints.txt and only releases uploaded before AGENTS_CUTOFF
# (the same rules as clients/python/run-all-tests.sh).
agent_pkgs="openai_agents langgraph google_adk"
agents_cutoff="${AGENTS_CUTOFF:-2026-10-01T00:00:00Z}"

compose() {
  docker compose --project-name haltsql-e2e --file "$here/compose.yaml" \
    --env-file "$env_file" "$@"
}

gen_env() {
  if [ -f "$env_file" ]; then return 0; fi
  umask 077
  rnd() { od -An -N16 -tx1 /dev/urandom | tr -d ' \n'; }
  {
    echo "# Generated by test/e2e/stack.sh; test-only secrets, never commit."
    echo "E2E_PG_PASSWORD=$(rnd)"
    echo "E2E_KC_ADMIN_PASSWORD=$(rnd)"
    echo "E2E_KC_CLIENT_SECRET=$(rnd)"
    echo "E2E_KC_USER_PASSWORD=$(rnd)"
    echo "E2E_MINIO_ROOT_PASSWORD=$(rnd)"
  } >"$env_file"
  echo "wrote $env_file"
}

up() {
  gen_env
  compose up --detach --wait --wait-timeout "${E2E_WAIT_TIMEOUT:-600}"
  compose ps --format '{{.Service}}: {{.Status}}'
}

down() {
  if [ -f "$env_file" ]; then
    compose down --volumes --remove-orphans --timeout 5
  else
    # Without the env file the ${VAR:?} checks in compose.yaml fail; down by label.
    docker ps -aq --filter label=com.docker.compose.project=haltsql-e2e | xargs -r docker rm -f
    docker volume ls -q --filter label=com.docker.compose.project=haltsql-e2e | xargs -r docker volume rm
  fi
}

venv() {
  local py="${PYTHON:-python3}"
  if [ ! -x "$venv/bin/python" ]; then "$py" -m venv "$venv"; fi
  "$venv/bin/python" -m pip install --quiet --disable-pip-version-check \
    -r "$here/requirements.txt" -c "$here/constraints.txt"
}

agents_python() {
  if [ -n "${PYTHON_AGENTS:-}" ]; then echo "$PYTHON_AGENTS"; return; fi
  local c
  for c in python3.12 python3.13 python3.11 python3; do
    if command -v "$c" >/dev/null 2>&1 &&
       "$c" -c 'import sys; sys.exit(0 if (3, 11) <= sys.version_info[:2] <= (3, 13) else 1)' 2>/dev/null; then
      echo "$c"; return
    fi
  done
  echo "no Python 3.11-3.13 for the agent frameworks (set PYTHON_AGENTS)" >&2
  return 1
}

venv_agents() {
  local repo apy pkg v
  repo="$(cd "$here/../.." && pwd)"
  apy="$(agents_python)"
  for pkg in $agent_pkgs; do
    v="$agents_venvs/$pkg"
    if [ ! -x "$v/bin/python" ]; then "$apy" -m venv "$v"; fi
    "$v/bin/python" -m pip install --quiet --disable-pip-version-check --upgrade pip
    "$v/bin/python" -m pip install --quiet --disable-pip-version-check \
      --uploaded-prior-to "$agents_cutoff" -c "$repo/integrations/$pkg/constraints.txt" \
      "$repo/clients/python[psycopg]" "$repo/integrations/$pkg"
  done
}

run_tests() {
  [ -x "$venv/bin/python" ] || venv
  # From test/e2e, so arguments are test files there (test_policy_distribution.py)
  # or node ids (test_policy_distribution.py::test_policy_distribution_over_oci).
  cd "$here"
  "$venv/bin/python" -m pytest "$@"
}

cmd="${1:-}"
[ $# -gt 0 ] && shift
case "$cmd" in
  env) gen_env ;;
  up) up ;;
  down) down ;;
  venv) venv; venv_agents ;;
  test) run_tests "$@" ;;
  ps) compose ps ;;
  logs) compose logs --no-color "$@" ;;
  run)
    if [ "${KEEP:-0}" != "1" ]; then trap down EXIT; fi
    up
    venv
    venv_agents
    HALTSQL_E2E_REQUIRE="${HALTSQL_E2E_REQUIRE:-1}" run_tests "$@"
    ;;
  *)
    sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
    ;;
esac
