def tests_for(path):
    if path == AC:
        # test_core.py is byte-identical in the five packages: run it once, then each framework file.
        return [("integrations/openai_agents", "v_openai_agents", [])] + [
            (f"integrations/{p}", f"v_{p}", [f"tests/test_{p}.py"]) for p in PKGS[1:]]
    if path == IN:
        return ([("clients/python", "pyv", ["tests/test_integration_helpers.py"])]
                + [(f"integrations/{p}", f"v_{p}", []) for p in ("langchain", "llamaindex", "vanna")]
                + [("integrations/openai_agents", "v_openai_agents", [])])
    for p in PKGS:
        if path.startswith(f"integrations/{p}/"):
            return [(f"integrations/{p}", f"v_{p}", [])]
    raise KeyError(path)


